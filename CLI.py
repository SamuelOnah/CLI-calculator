def add(a,b):
    return a + b
result = add(10, 5)
print(result)
print(add(-3, 8))
print(add(-5, -2))

def subtract(a,b):
    return a - b
result = subtract(10,5)
print(subtract(3,8))
print(result)


def multiply(a, b):
    return a * b
print(multiply(4,3))
print(multiply(-4,3))
print(multiply(-4,-3))

